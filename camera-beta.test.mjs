import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
for (const f of ['camera-beta.js','gamefeel.js','player.js','netplayer.js','balance.js','game.js']) assert.ok(readFileSync(f,'utf8').length>0, f+' vacío');
const g = readFileSync('game.js','utf8');
assert.ok(g.includes('initCamBeta()'), 'la cámara debe inicializarse');
assert.ok(g.includes('betaLoop'), 'debe haber un bucle que aplique la cámara');
assert.ok(g.includes('playerTick(dt)'), 'el personaje debe actualizarse');
assert.ok(g.includes('fxTick(dt)'), 'los efectos deben actualizarse');
assert.ok(g.includes('netPlayerTick(dt)'), 'el compañero debe interpolarse');
assert.ok(g.includes('applyBalance()'), 'el equilibrio debe aplicarse');
assert.ok(g.includes('pointerdown'), 'debe haber control táctil');
const cam = readFileSync('camera-beta.js','utf8');
assert.ok(cam.includes('autoDelay'), 'la cámara automática debe tener retardo');
const pl = readFileSync('player.js','utf8');
assert.ok(pl.includes('navFind'), 'el personaje debe usar la navegación existente');
console.log('OK camera-beta: 5 entregas integradas en el bucle, control táctil y equilibrio aplicados.');
