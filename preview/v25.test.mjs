import assert from 'node:assert/strict';
import * as O from './opinions-model.mjs';
import * as R from './ratings-model.mjs';
import * as M from './progression-model.mjs';
import * as S from './social-model.js';
import * as I from './influencer-model.mjs';
import { readFileSync } from 'node:fs';
const visits=Array.from({length:60},(_,i)=>({type:'turista',hour:10+i/10,sat:i%5===0?0.2:0.97,order:['cerveza'],lost:i%11===0?'caro':(i%13===0?'espera':null),priceF:0}));
const a=O.decideAll(visits,3,R.visitStars),b=O.decideAll(visits,3,R.visitStars);
assert.deepEqual(a,b);
assert(a.every(o=>!o.comment||o.rated));
assert(a.every((o,i)=>visits[i].lost!=='caro'||!o.rated));
const c=O.opinionCounts({visits,opinions:a});
assert.equal(c.visitors,60);assert(c.rated>0&&c.rated<c.visitors);assert(c.comments<=c.rated);
assert.equal(O.publicRating(visits,a,R.visitStars).count,c.rated);
assert.equal(O.publicRating(visits,visits.map(()=>({rated:false})),R.visitStars).avg,null);
assert(R.reputation(3,Array.from({length:80},()=>({sat:0.99})))-3<=0.2+1e-9);
assert(R.reputation(4,Array.from({length:80},()=>({lost:'espera'})))>=3.65-1e-9);
assert.equal(R.incidentCause({lost:'caro'}),'precio');assert.equal(R.incidentCause({lost:'espera'}),'espera');
let p=M.initial('t');p.goal=M.goalFor(p,1);
const base={day:1,served:30,lost:2,rating:3.2,waste:1,revenue:200,sales:215,profit:50,cash:500,cashDelta:60,followers:60};
const o=M.settle(p,base);assert(o.applied);p=o.p;
assert.equal(M.settle(p,base).applied,false);
const am=M.amend(p,{day:1,profit:46,cash:496});
assert(am.changed);assert.equal(am.p.history.length,1);assert.equal(am.p.history[0].profit,46);assert.equal(am.p.history[0].sales,215);
assert.equal(M.amend(am.p,{day:1,profit:46,cash:496}).changed,false);
assert.equal(M.amend(am.p,{day:2,profit:1}).changed,false);
assert.equal(R.visitStars({sat:0.91}),5);assert.equal(R.visitStars({sat:0.89}),4);assert.equal(R.visitStars({sat:0.99,upset:true}),4);
for(const [k,lo] of [['micro',250],['medio',300],['grande',450]])for(const sales of [lo,600,900]){const cost=I.influCost(k,sales),roi=I.influRoi({arr:I.INFLU_ARR[k],cost,sales});assert(roi>=1.1&&roi<=1.45,k+' '+sales+' '+roi.toFixed(2));}
assert.equal(I.influCost('micro',0),I.influCost('micro',250));
assert(/spoil:0\.75, spoilF:0\.25/.test(readFileSync('config.js','utf8')));
const mx=S.postMetrics({fx:{reach:1.2,eng:1.1},f:100});
assert(mx.reach>0&&mx.interactions<=mx.reach&&mx.likes+mx.comments===mx.interactions);
const st=S.settle({f:100,rep:4,pend:[{k:'Pub',n:5,post:true}]});
assert.equal(st.total,100+st.gainSum-st.lossSum);
console.log('OK v25: opiniones deterministas, valoracion publica, reputacion gradual, historial corregible sin duplicar y metricas sociales.');
